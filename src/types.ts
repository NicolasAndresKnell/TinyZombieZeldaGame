// Shared types for config, level data and network messages.

export interface Vec { x: number; y: number }

export type Direction = 'down' | 'up' | 'left' | 'right';

// One letter per map tile (see world/terrain.ts for what each means).
export type TileKind = 'S' | 'P' | 'A' | 'G' | 'R' | 'T' | '1' | '2' | '3' | 'W' | 'B' | 'K';

export type EnemyTypeName = 'walker' | 'spitter' | 'brute' | 'boss';
export type EnemySheet = `zombie_${EnemyTypeName}`;

export interface EnemyType {
  sheet: EnemySheet;
  health: number; scale: number;
  wanderSpeed: number; chaseSpeed: number; chaseRange: number;
  attack: 'melee' | 'spit' | 'slam' | 'boss';
  damage: number; windupMs: number; attackMs: number; cooldownMs: number;
  stunMs: number; knockTaken: number;          // knockTaken < 1: heavy, shrugs off hits mid-attack
  range?: number; reach?: number;              // melee / slam trigger distance
  keepAway?: [number, number];                 // spitters hold this distance band
  slamRadius?: number; spitSpeed?: number;
}

// Generated by tools/level.py: [tileX, tileY, height level]
export type TileSpot = [number, number, number];

export interface LevelData {
  w: number; h: number;
  tiles: string;                               // w*h TileKind letters, row by row
  start: [number, number];
  props: [string, number, number][];           // [texture, pixel x, pixel y of the base]
  zombies: TileSpot[];
  brains: TileSpot[];
}

// Generated by tools/pack.py: animation name -> [first frame, frame count]
export type AnimTable = Record<string, [number, number]>;

export interface SpriteData {
  heroAnims: AnimTable;
  zombieAnims: AnimTable;
  propSizes: Record<string, [number, number]>;
}

// What each player sends about their hero.
export interface HeroState {
  x: number; y: number;
  lv: number;                                  // height level
  f: Direction;                                // facing
  a: string;                                   // current animation key
  d: boolean;                                  // dead
}

export interface Peer { id: string; hero: HeroState }
